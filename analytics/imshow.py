img = Image.open("scene.jpg")
draw = ImageDraw.Draw(img)

W, H = img.size  # image width and height

for (x, y, w, h) in bboxes:
    # Convert bottom-left origin → top-left origin
    top_left_y = H - (y + h)

    # Compute rectangle corners
    x1 = x
    y1 = top_left_y
